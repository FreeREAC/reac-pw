# packaging/reac-pw-nm-unmanaged.sh WRITES NETWORKMANAGER'S DROP-IN FROM THE MARKS reac-pw
# PUTS ON ITS INTERFACES, AND FROM NOTHING ELSE.
#
# sysfs, /proc/sys, nmcli and ip are replaced (REACPW_NM_*), so this asserts what the script
# DECIDES and writes, with no NetworkManager and no root. The arms:
#   A. a marked NIC and a minted VLAN become unmanaged-devices; a host alias and an
#      unmarked NIC do not; NetworkManager is told; the link is brought up, IPv6 off;
#   B. the same marks again change nothing and tell NetworkManager nothing;
#   C. a mark that goes away (a clean daemon exit) keeps the interface in the set;
#   D. a new mark is added beside the old ones;
#   E. a name that is not an interface name is never written;
#   F. --forget hands one interface back; --remove deletes the file.
set -u

script=${1:?usage: nm-unmanaged-follows-the-marks.sh <path to reac-pw-nm-unmanaged.sh>}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
fail=0

sys=$work/sys proc=$work/proc conf=$work/etc/conf.d/90-reac-pw.conf calls=$work/calls
mkdir -p "$sys" "$proc"
for cmd in nmcli ip; do
    printf '#!/bin/sh\necho "%s $*" >>"%s"\n' "$cmd" "$calls" >"$work/$cmd"
    chmod +x "$work/$cmd"
done

# nic <name> <alias> <flags>
nic() {
    mkdir -p "$sys/$1" "$proc/$1"
    printf '%s\n' "$2" >"$sys/$1/ifalias"
    printf '%s\n' "$3" >"$sys/$1/flags"
    echo 0 >"$proc/$1/disable_ipv6"
}

run() {
    : >"$calls"
    REACPW_NM_SYSFS=$sys REACPW_NM_PROCSYS=$proc REACPW_NM_CONF=$conf \
        REACPW_NM_NMCLI=$work/nmcli REACPW_NM_IP=$work/ip sh "$script" "$@" 2>"$work/stderr"
}

devices() { sed -n 's/^unmanaged-devices+=//p' "$conf" 2>/dev/null; }

check() {   # check <arm> <what> <condition...>
    local arm=$1 what=$2; shift 2
    if "$@"; then :; else
        echo "FAIL $arm: $what"
        echo "  conf: $(devices)"; echo "  calls:"; sed 's/^/    /' "$calls"
        sed 's/^/  stderr: /' "$work/stderr"
        fail=1
    fi
}

nic enp1s0   "reac-pw:served" 0x1002   # marked, admin DOWN
nic enp1s0.11 "reac-pw:minted" 0x1003  # minted VLAN, up
nic lab0     "lab-port"       0x1003   # the host's own alias
nic wlan0    ""               0x1003   # nothing to do with REAC
nic lo       ""               0x9

# A
run
check A "marked NIC and minted VLAN unmanaged, nothing else" \
    test "$(devices)" = "interface-name:enp1s0;interface-name:enp1s0.11"
check A "NetworkManager re-reads its configuration" grep -qx "nmcli general reload conf" "$calls"
check A "the marked NIC is set unmanaged now" grep -qx "nmcli device set enp1s0 managed no" "$calls"
check A "the down NIC is brought up" grep -qx "ip link set dev enp1s0 up" "$calls"
check A "an up link is not touched" bash -c "! grep -q 'ip link set dev enp1s0.11' '$calls'"
check A "IPv6 off on the REAC NIC" test "$(cat "$proc/enp1s0/disable_ipv6")" = 1
check A "IPv6 untouched on the host's NIC" test "$(cat "$proc/lab0/disable_ipv6")" = 0
check A "the file says it is generated" test "$(head -n1 "$conf" | cut -c1-35)" = "# GENERATED by reac-pw-nm-unmanaged"
check A "under [keyfile]" grep -qx "\[keyfile\]" "$conf"

# B (the fake `ip` changes nothing, so the link it brought up is raised here)
printf '0x1003\n' >"$sys/enp1s0/flags"
run
check B "same set: nothing written, NetworkManager not asked" test ! -s "$calls"

# C
printf '\n' >"$sys/enp1s0/ifalias"
run
check C "a mark removed at exit keeps the interface unmanaged" \
    test "$(devices)" = "interface-name:enp1s0;interface-name:enp1s0.11"
check C "and nothing is reloaded" bash -c "! grep -q nmcli '$calls'"

# D
nic enp2s0 "reac-pw:served" 0x1003
run
check D "a new mark joins the set" \
    test "$(devices)" = "interface-name:enp1s0;interface-name:enp1s0.11;interface-name:enp2s0"
check D "only the new one is set unmanaged" grep -qx "nmcli device set enp2s0 managed no" "$calls"
check D "the old one is not set again" bash -c "! grep -q 'device set enp1s0 ' '$calls'"

# E
nic "x;y" "reac-pw:served" 0x1003
nic "averyveryverylongname" "reac-pw:served" 0x1003
run
check E "an invalid or overlong name never reaches the file" \
    test "$(devices)" = "interface-name:enp1s0;interface-name:enp1s0.11;interface-name:enp2s0"
rm -rf "$sys/x;y" "$sys/averyveryverylongname"

# F
run --forget enp1s0.11
check F "--forget hands one interface back" \
    test "$(devices)" = "interface-name:enp1s0;interface-name:enp2s0"
check F "--forget tells NetworkManager" grep -qx "nmcli general reload conf" "$calls"
run --remove
check F "--remove deletes the drop-in" test ! -e "$conf"
check F "--remove tells NetworkManager" grep -qx "nmcli general reload conf" "$calls"

[ "$fail" -eq 0 ] || exit 1
echo "OK: the NetworkManager drop-in is the union of reac-pw's marks, and only of them"
