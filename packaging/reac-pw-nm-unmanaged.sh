# reac-pw-nm-unmanaged -- the ONE writer of NetworkManager's drop-in for REAC interfaces.
#
# WHY. A REAC wire is raw Layer 2: no address, no DHCP, no network manager. On the desk
# (2026-10-11) the REAC NIC was NetworkManager-managed; with no box answering, reac-pw's
# wake ladder bounces the link, NetworkManager deleted and re-added the link-local
# addresses on every edge, and each address change made the browser abort every socket it
# had, the console's own on 127.0.0.1 included.
#
# WHERE THE DEVICE SET COMES FROM. reac-pw runs as a user service and cannot write here, so
# it says which interfaces are REAC wires ON THE INTERFACE: every NIC a segment comes up on
# carries the alias `reac-pw:served`, and every VLAN it mints carries `reac-pw:minted`
# (src/reac_served_mark.h). This script reads those aliases. It names no interface and
# reads no setting of its own.
#
# WHAT IT KEEPS. The set is the union of the interfaces in its own drop-in and the ones
# carrying a `reac-pw:` alias now, so an interface stays unmanaged across a reboot, before
# reac-pw has started and marked it again. For each interface in the set that exists it
# also brings the link up and disables IPv6 on it, which is what NetworkManager did for it
# before: without that, an unmanaged NIC stays down at boot (reac-pw only listens on a
# linked interface) and the kernel itself adds an IPv6 link-local address on every link-up.
#
#   reac-pw-nm-unmanaged            sync once
#   reac-pw-nm-unmanaged --watch    sync, then again on every link change (the service)
#   reac-pw-nm-unmanaged --forget IFACE
#                                   hand IFACE back to NetworkManager (until reac-pw
#                                   serves it again)
#   reac-pw-nm-unmanaged --remove   delete the drop-in (package removal)
#
# The paths and commands below can be pointed elsewhere for tests/reac-pw-nm-unmanaged.sh;
# nothing in a real install sets them.
set -u

SYSFS=${REACPW_NM_SYSFS:-/sys/class/net}
PROCSYS=${REACPW_NM_PROCSYS:-/proc/sys/net/ipv6/conf}
CONF=${REACPW_NM_CONF:-/etc/NetworkManager/conf.d/90-reac-pw.conf}
NMCLI=${REACPW_NM_NMCLI:-nmcli}
IP=${REACPW_NM_IP:-ip}

say() { echo "reac-pw-nm-unmanaged: $*" >&2; }

# A Linux interface name: 1-15 bytes, no '/', no whitespace, not '.' or '..'. Anything
# else in the drop-in or in sysfs is not written back.
valid_name() {
    case $1 in
        ''|.|..|*/*|*' '*|*'	'*|*';'*|*','*) return 1 ;;
    esac
    [ "${#1}" -le 15 ]
}

# The interfaces this script's own drop-in names, one per line.
known() {
    [ -f "$CONF" ] || return 0
    sed -n 's/^unmanaged-devices+=//p' "$CONF" | tr ';' '\n' |
        sed -n 's/^interface-name://p'
}

# The interfaces carrying a reac-pw: alias now, one per line.
marked() {
    for d in "$SYSFS"/*; do
        [ -r "$d/ifalias" ] || continue
        case $(cat "$d/ifalias" 2>/dev/null) in
            reac-pw:*) basename "$d" ;;
        esac
    done
}

nm_reload() {
    command -v "$NMCLI" >/dev/null 2>&1 || return 0
    "$NMCLI" general reload conf >/dev/null 2>&1 ||
        say "could not ask NetworkManager to re-read its configuration (is it running?)"
}

write_conf() {   # write_conf <name>...
    if [ $# -eq 0 ]; then
        rm -f "$CONF"
        return
    fi
    list=
    for n in "$@"; do list="${list:+$list;}interface-name:$n"; done
    mkdir -p "$(dirname "$CONF")" || return 1
    tmp="$CONF.tmp.$$"
    {
        echo "# GENERATED by reac-pw-nm-unmanaged (reac-pw). Do not edit: it is rewritten"
        echo "# whenever the set of REAC interfaces changes, and removed with reac-pw."
        echo "# Hand an interface back to NetworkManager with"
        echo "#   reac-pw-nm-unmanaged --forget <interface>"
        echo "[keyfile]"
        echo "unmanaged-devices+=$list"
    } >"$tmp" && mv -f "$tmp" "$CONF"
}

# What NetworkManager did for a REAC NIC before it was told to leave it alone: link up,
# no IPv6 (the kernel's own link-local address would come back on every link-up).
prepare() {   # prepare <name>
    [ -e "$SYSFS/$1" ] || return 0
    v6="$PROCSYS/$1/disable_ipv6"
    if [ -w "$v6" ] && [ "$(cat "$v6" 2>/dev/null)" != 1 ]; then
        echo 1 >"$v6" 2>/dev/null || say "could not disable IPv6 on $1"
    fi
    flags=$(cat "$SYSFS/$1/flags" 2>/dev/null || echo 0x1)
    if [ $((flags & 1)) -eq 0 ]; then
        "$IP" link set dev "$1" up 2>/dev/null || say "could not bring $1 up"
    fi
}

# Tell a running NetworkManager now, not only at its next start: a re-read of the
# configuration, and the device itself set unmanaged in case this NetworkManager does not
# apply unmanaged-devices on a re-read.
nm_unmanage_now() {   # nm_unmanage_now <name>...
    nm_reload
    command -v "$NMCLI" >/dev/null 2>&1 || return 0
    for n in "$@"; do
        [ -e "$SYSFS/$n" ] || continue
        "$NMCLI" device set "$n" managed no >/dev/null 2>&1 || :
    done
}

sync_once() {
    old=$(known | sort -u)
    new=$( { known; marked; } | while read -r n; do valid_name "$n" && echo "$n"; done |
           sort -u)
    [ "$new" = "$old" ] || {
        # shellcheck disable=SC2086 # one interface name per word, validated above
        write_conf $new || { say "could not write $CONF"; return 1; }
        added=
        for n in $new; do
            printf '%s\n' "$old" | grep -qxF "$n" || added="$added $n"
        done
        say "REAC interfaces NetworkManager leaves alone: $(echo $new) (new:$added)"
        # shellcheck disable=SC2086
        nm_unmanage_now $added
    }
    for n in $new; do prepare "$n"; done
}

case "${1:-}" in
    '')
        sync_once
        ;;
    --watch)
        sync_once
        # Every link change: a mark written or removed, an interface appearing (a USB
        # NIC plugged, a VLAN minted). A sync that finds the same set writes nothing.
        "$IP" -o monitor link | while read -r _; do sync_once; done
        ;;
    --forget)
        n=${2:?usage: reac-pw-nm-unmanaged --forget <interface>}
        rest=$(known | grep -vxF "$n" | sort -u)
        # shellcheck disable=SC2086
        write_conf $rest || exit 1
        say "$n handed back to NetworkManager"
        nm_reload
        ;;
    --remove)
        if [ -f "$CONF" ]; then
            rm -f "$CONF"
            nm_reload
        fi
        ;;
    *)
        echo "usage: reac-pw-nm-unmanaged [--watch | --forget <interface> | --remove]" >&2
        exit 2
        ;;
esac
